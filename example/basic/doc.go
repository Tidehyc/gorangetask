// Package basic 是一个最小但**可独立运行**的示例：它演示 GoRangeTask 的核心用法
// ——把业务行与任务行写进**同一个 MySQL 事务**，再让 Worker 执行本进程注册的
// Handler 把业务记录推进到终态。
//
// 它刻意不引入任何业务框架，领域也只有"订单"一张表：目的是让用法可以照着跑、
// 照着读。需求文档 §10.3 要求示例能证明三件事，本包用真库集成测试逐条兑现：
//
//  1. 事务提交后业务行与任务行**同时**存在；
//  2. 事务回滚后两者**同时**不存在；
//  3. Worker 跑起来后业务记录被推进到 exported，且任务进入 succeeded 终态。
//
// # 为什么"同事务"是重点
//
// 任务行和业务行分开写就会出现经典的不一致：业务提交了、任务没投出去（任务永远
// 不会被执行），或者任务投出去了、业务回滚了（Handler 去处理一条不存在的业务记录）。
// 两种都只能靠外部对账发现。GoRangeTask 的 EnqueueTx 接收调用方**已经在用**的
// 事务执行器，让两者共用同一次提交，这两种不一致因此都不会出现——见
// Store.CreateOrder。
//
// # 至少一次语义与幂等
//
// 库只保证任务**至少**被交付一次：进程崩溃、租约过期、停机超时都会让同一条任务
// 被重新领取。因此 Handler 必须幂等——见 ExportOrderHandler，它用一条条件更新
// 把"重复执行"变成"第二次什么都不做"。
//
// # 怎么跑
//
